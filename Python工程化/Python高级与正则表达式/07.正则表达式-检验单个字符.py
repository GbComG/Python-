"""
案例：演示正则表达式之 检验单个字符。
正则表达式介绍：
概念：
正确的，符合特定规则的字符串。
Regular Expression，正则表达式，简称：re，regexp

部分：
1、学习正则表达式，就是学正则表达式的规则，你用不着，网上一搜一大堆。
2、关于正则对大家的要求，能用我们讲的规则，看懂别人写的式子，且会简单修改即可。
3、正则不独属于 Python，像 Java，JavaScript，PHP，Go 等都支持。

步骤：
1. 导入
import re
2. 正则匹配
result = re.match("正则表达式", "要被检验的字符串")
3. 获取匹配结果
result.group()

正则常用的规则：
. 代表任意的 1 个字符，除了 \n
\\取消特殊含义，变成普通的。
a 代表 1 个普通的字符 a
[abc] 代表 a,b,c 中任意的 1 个字符
[^abc] 代表除 a,b,c 外，任意的 1 个字符
\\d 代表数字，等价于 [0-9]
\\D 代表非数字，等价于 [^0-9]
\\s 代表空白字符（空格、tab、换行等）
\\S 代表非空白字符
\\w 代表单词字符：字母、数字、下划线
\\W 代表非单词字符

^   匹配开头
$   匹配结尾
*   匹配前面的字符 0 次或多次
?   匹配前面的字符 0 次或 1 次
+   匹配前面的字符 1 次或多次
{n}   匹配前面的字符恰好 n 次
{n,}  匹配前面的字符至少 n 次
{n,m} 匹配前面的字符 n ~ m 次
|     或
()    分组
\num  引用第 num 组

扩展：
(?P<分组名>) 命名分组
(?P=分组名) 引用命名分组

"""

#需求：正则入门

#1.导包
import re

#2.正则校验
result = re.match('.it','ait') #匹配成功
result1 = re.match('.it','你it') #匹配成功
result3 = re.match('.it','你好it') #匹配失败

#3.获取匹配结果
if result:
    print(result.group())
else:
    print('匹配失败')

