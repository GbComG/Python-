"""
案例：深浅拷贝
记忆（总结）:
    1.所谓深浅拷贝指的是
        浅拷贝:copy模块的copy()
        深拷贝:copy模块的deepcopy()函数
    2.大白话解释
        深拷贝拷贝的对，浅拷贝拷贝的少
    3.深浅拷贝主要针对可变类型来讲的，深拷贝拷贝所有层(可变),浅拷贝只拷贝第一层.
    如果是针对于不可变类型，则和普通赋值没区别
"""

#浅拷贝
import copy

a = [[1, 2], "hello"]
b = copy.copy(a)

print(a is b)       # False：外层列表不是同一个对象
print(a[0] is b[0]) # True：内层列表是同一个对象
print(a[1] is b[1]) # True：字符串对象也是同一个对象

# 自我总结：

#简单来说，对于可变类型的浅拷贝，它只能将被拷贝变量的外层容器复制一份，形成一个独立的新对象，而内层元素的引用仍然指向同一个内存地址，也就是说，内层对象是共享的。如果修改共享的可变对象本身，两个变量都会受到影响。

#而对于不可变类型的浅拷贝，浅拷贝同样会复制外层容器，并复制内层元素的引用。此时，两个变量中的对应元素通常指向同一个对象。但是，由于不可变对象本身不能被修改，当我们对其中一个变量的对应位置重新赋值时，实际上是让这个位置指向一个新的对象，而不是修改原有对象。因此，虽然从 `print()` 的输出结果可能无法判断它们是否共享引用，但可以通过 `is` 和 `id()` 观察对象身份的区别。

#深拷贝 不管有几层，只要是可变类型就拷贝并创建一个新的内存地址，遇见不可变类型就直接引用
import copy

a = [1, [2, 3]]
b = copy.deepcopy(a)

print(a is b)       # False：外层列表不同
print(a[1] is b[1]) # False：内层列表也不同
b[1].append(4)

print(a)  # [1, [2, 3]]
print(b)  # [1, [2, 3, 4]]